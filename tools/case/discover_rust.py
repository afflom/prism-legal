"""Build and run the certified Rust discovery harness against the crates emitted from `src/Discovery.lex.tex`.

`lexlean production build` publishes `prism_legal_discovery_build_columns`,
`prism_legal_discovery_find_relations`, and `prism_legal_discovery_find_recurrence`
under `.lexlean/production/<bundle>/packages/rust-std/`. This module builds a Cargo
harness crate in `.lexlean/discover-harness/` against those certified packages."""

import json
import subprocess

from . import ROOT, production

HARNESS = ROOT / ".lexlean" / "discover-harness"
BIN = HARNESS / "target" / "release" / "prism_legal_discover_harness"
CRATES = {
    "buildColumns": "prism_legal_discovery_build_columns",
    "findRelations": "prism_legal_discovery_find_relations",
    "findRecurrence": "prism_legal_discovery_find_recurrence",
}


def bundles():
    root = production.OUT
    if not root.exists():
        return []
    found = []
    for result in root.glob("*/result.json"):
        pkgs = result.parent / "packages" / "rust-std"
        if all((pkgs / crate / "Cargo.toml").exists() for crate in CRATES.values()):
            found.append(result.parent)
    return sorted(found, key=lambda p: p.stat().st_mtime, reverse=True)


MAIN_RS = r"""// Generated by tools/case/discover_rust.py
use std::io::{self, BufRead, Write};

fn nats<L>(xs: &[u64], nil: fn() -> L, cons: fn(u64, L) -> L) -> L {
    let mut out = nil();
    for x in xs.iter().rev() { out = cons(*x, out); }
    out
}

fn main() {
    let worker = std::thread::Builder::new().stack_size(1 << 30).spawn(serve).expect("thread");
    worker.join().expect("the harness thread");
}

fn serve() {
    let stdin = io::stdin();
    let mut out = io::BufWriter::new(io::stdout());
    for line in stdin.lock().lines() {
        let line = line.expect("stdin");
        let mut it = line.split_whitespace();
        let kind = match it.next() { Some(k) => k.to_string(), None => continue };
        let nums: Vec<u64> = it.map(|x| x.parse().expect("a natural")).collect();
        let answer = match kind.as_str() {
            "columns" => columns(&nums),
            "relations" => relations(&nums),
            "recurrence" => recurrence(&nums),
            other => format!("error unknown request {}", other),
        };
        writeln!(out, "{}", answer).expect("stdout");
    }
}

__ADAPTERS__
"""


def harness_source():
    c, r, q = CRATES["buildColumns"], CRATES["findRelations"], CRATES["findRecurrence"]
    adapters = f"""
fn words_c(xs: &[u64]) -> {c}::List<u64> {{ nats(xs, {c}::List::nil, {c}::List::cons) }}
fn words_r(xs: &[u64]) -> {r}::List<u64> {{ nats(xs, {r}::List::nil, {r}::List::cons) }}
fn unlist_c<T: Clone>(l: &{c}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}
fn unlist_r<T: Clone>(l: &{r}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}
fn unlist_q<T: Clone>(l: &{q}::List<T>) -> Vec<T> {{
    let mut out = Vec::new();
    let mut cur = l.clone();
    while let Some((h, t)) = cur.uncons() {{ out.push(h); cur = t; }}
    out
}}

fn columns(n: &[u64]) -> String {{
    let (width, nb, ns) = (n[0], n[1] as usize, n[2] as usize);
    let per = (n.len() - 3 - 3 * ns) / nb;
    let mut bases = {c}::List::nil();
    for i in (0..nb).rev() {{ bases = {c}::List::cons(words_c(&n[3 + i * per..3 + (i + 1) * per]), bases); }}
    let off = 3 + nb * per;
    let mut specs = {c}::List::nil();
    for i in (0..ns).rev() {{
        let s = &n[off + 3 * i..off + 3 * i + 3];
        specs = {c}::List::cons((s[0], (s[1], s[2])), specs);
    }}
    match {c}::run(width, bases, specs) {{
        Ok(cols) => unlist_c(&cols).iter().map(|w| unlist_c(w).iter().map(|x| x.to_string()).collect::<Vec<_>>().join(",")).collect::<Vec<_>>().join(" "),
        Err(_) => "violation overflow".to_string(),
    }}
}}

fn relations(n: &[u64]) -> String {{
    let (width, m) = (n[0], n[1] as usize);
    let per = (n.len() - 2) / m;
    let mut cols = {r}::List::nil();
    for i in (0..m).rev() {{ cols = {r}::List::cons(words_r(&n[2 + i * per..2 + (i + 1) * per]), cols); }}
    match {r}::run((width, cols)) {{
        Ok(Ok(rels)) => unlist_r(&rels).iter().map(|m| unlist_r(m).iter().map(|b| if *b {{ '1' }} else {{ '0' }}).collect::<String>()).collect::<Vec<_>>().join(" "),
        Ok(Err((a, b))) => format!("violation {{}}{{}}", a as u8, b as u8),
        Err(_) => "violation overflow".to_string(),
    }}
}}

fn recurrence(n: &[u64]) -> String {{
    let k = n[0] as usize;
    let mut bits = {q}::List::nil();
    for i in (0..k).rev() {{ bits = {q}::List::cons(n[1 + i] == 1, bits); }}
    match {q}::run(bits) {{
        Ok(Ok(c)) => unlist_q(&c).iter().map(|b| if *b {{ '1' }} else {{ '0' }}).collect::<String>(),
        Ok(Err((a, b))) => format!("violation {{}}{{}}", a as u8, b as u8),
        Err(_) => "violation overflow".to_string(),
    }}
}}
"""
    return MAIN_RS.replace("__ADAPTERS__", adapters)


def cargo_toml(bundle):
    pkgs = bundle / "packages" / "rust-std"
    deps = "\n".join(f'{crate} = {{ path = "{pkgs / crate}" }}' for crate in sorted(CRATES.values()))
    return (
        '[package]\nname = "prism_legal_discover_harness"\nversion = "0.1.0"\nedition = "2021"\npublish = false\n\n'
        "[dependencies]\n"
        + deps
        + "\n\n[profile.release]\nopt-level = 3\n"
    )


def ensure_binary():
    found = bundles()
    if not found:
        res = production.build(verify=False)
        if not res["ok"]:
            raise RuntimeError(f"lexlean production build failed: {json.dumps(res)}")
        found = bundles()
    bundle = found[0]
    (HARNESS / "src").mkdir(parents=True, exist_ok=True)
    stamp = json.dumps({"bundle": str(bundle)})
    files = {
        HARNESS / "Cargo.toml": cargo_toml(bundle),
        HARNESS / "src" / "main.rs": harness_source(),
        HARNESS / "bundle.json": stamp,
    }
    changed = False
    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            changed = True
    if changed or not BIN.exists():
        r = subprocess.run(
            ["cargo", "build", "--release", "--offline", "--quiet"],
            cwd=HARNESS,
            capture_output=True,
            text=True,
        )
        if r.returncode != 0:
            raise RuntimeError(f"cargo build failed: {r.stderr or r.stdout}")
    return BIN


def _ask(lines):
    binary = ensure_binary()
    r = subprocess.run([str(binary)], input="\n".join(lines) + "\n", capture_output=True, text=True, check=True)
    answers = r.stdout.splitlines()
    for a in answers:
        if a.startswith(("violation", "error")):
            raise RuntimeError(f"certified root refused: {a}")
    return answers


def find_relations(width, bases, specs):
    flat = [w for b in bases for w in b] + [x for s in specs for x in s]
    col_line = f"columns {width} {len(bases)} {len(specs)} " + " ".join(map(str, flat))
    (col_ans,) = _ask([col_line])
    cols = [[int(x) for x in col.split(",")] if col else [] for col in col_ans.split(" ")] if col_ans else []
    rel_line = f"relations {width} {len(cols)} " + " ".join(str(x) for w in cols for x in w)
    (rel_ans,) = _ask([rel_line])
    return [[int(ch) for ch in m] for m in rel_ans.split()] if rel_ans else []


def find_recurrences(sequences):
    if not sequences:
        return []
    lines = [f"recurrence {len(bits)} " + " ".join("1" if b else "0" for b in bits) for bits in sequences]
    return [[int(ch) for ch in a] for a in _ask(lines)]
