import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE, args:['--no-sandbox']});
const page = await browser.newPage({viewport:{width:1280,height:1000}});
const failures=[];
page.on('pageerror', error=>failures.push(error.message));
await page.goto(process.env.BROWSER_URL || 'http://127.0.0.1:8793/',{waitUntil:'networkidle'});
await page.locator('#field-content').waitFor();
assert.equal(await page.locator('#field-content').inputValue(),'');
await page.locator('#field-content').fill('notice received\nnotice disputed');
await page.getByRole('button',{name:'Update understanding',exact:true}).click();
await page.getByText('Next: review this passage and its suggested facet.',{exact:true}).waitFor();
assert(await page.getByText('Unassigned',{exact:true}).isVisible());
await page.locator('#field-quotation').fill('notice received');
await page.locator('#field-facet').fill('Notice');
await page.getByRole('button',{name:'Update understanding',exact:true}).click();
await page.getByText('Line 2',{exact:true}).waitFor();
assert(await page.getByText('Notice',{exact:true}).isVisible());
await page.locator('#field-interpretation').fill('payment completed');
assert.equal(await page.getByText('Next: review this passage and its suggested facet.',{exact:true}).count(),0);
await page.locator('#field-audience').selectOption('lawyer');
await page.getByRole('button',{name:'Update understanding',exact:true}).click();
await page.getByText('Unassigned',{exact:true}).waitFor();
await page.getByText('Source 1, revision 1, UTF-8 bytes 0..15',{exact:true}).waitFor();
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth));
assert.deepEqual(failures,[]);
await browser.close();
console.log('PASS: generated browser starts empty, updates facets, clears stale results, shows provenance, and fits mobile without runtime errors');
